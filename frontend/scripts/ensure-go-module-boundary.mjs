import { writeFile } from "node:fs/promises";
import { fileURLToPath, URL } from "node:url";

const boundaryPath = fileURLToPath(
  new URL("../node_modules/go.mod", import.meta.url),
);
const boundary = `// Generated by the Cairn frontend postinstall hook.
// This prevents root Go commands from compiling unrelated .go files shipped
// inside npm dependencies.
module github.com/RCooLeR/Cairn/frontend/node_modules

go 1.27.0
`;

await writeFile(boundaryPath, boundary, { encoding: "utf8" });
